def text_size(text, scale):
    """Return the (width, height) in pixels of the rendered text."""
    if not text:
        return 0, GLYPH_HEIGHT * scale
    width = (
        len(text) * GLYPH_WIDTH * scale
        + (len(text) - 1) * GLYPH_SPACING * scale
    )
    return width, GLYPH_HEIGHT * scale


def draw_text(surface, text, x, y, scale, color):
    """Draw text at (x, y) using the bitmap font."""
    cursor_x = x
    for char in text.upper():
        glyph = _GLYPHS.get(char, _GLYPHS["?"])
        for row_index, row in enumerate(glyph):
            for col_index, cell in enumerate(row):
                if cell == "1":
                    rect = pygame.Rect(
                        cursor_x + col_index * scale,
                        y + row_index * scale,
                        scale,
                        scale,
                    )
                    surface.fill(color, rect)
        cursor_x += (GLYPH_WIDTH + GLYPH_SPACING) * scale


def draw_text_centered(surface, text, center_x, center_y, scale, color):
    """Draw text centred on (center_x, center_y)."""
    width, height = text_size(text, scale)
    draw_text(
        surface,
        text,
        center_x - width // 2,
        center_y - height // 2,
        scale,
        color,
    )
